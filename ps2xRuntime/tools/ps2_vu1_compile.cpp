// Compiles VU1 microcode images ahead of time into C++ that the runtime uses in place of the interpreter
// when the uploaded code matches (see VU1Interpreter::CompiledRun).
//   ps2_vu1_compile <out.cpp> <image.bin>...
// Images are whole 16 KiB VU1 code memories, as written by PS2X_VU1_DUMP_CODE=<dir>. Each pair becomes the
// interpreter's step with its decoding as a constant, so timing and results stay those of the interpreter.
#include "../src/lib/vu/ps2_vu1_step.h"

#include <cstdio>
#include <string>
#include <vector>

// ps2_runtime expects the generated runner to provide its function table; this tool runs no guest code.
struct R5900Context;
class PS2Runtime;
extern const uint32_t g_ps2RecompiledFunctionTableBase = 0u;
extern const uint32_t g_ps2RecompiledFunctionTableEnd = 0u;
extern const uint32_t g_ps2RecompiledFunctionTableSlotCount = 0u;
void (*g_ps2RecompiledFunctionTable[1])(uint8_t *, R5900Context *, PS2Runtime *) = {nullptr};

namespace
{
    using A = Vu1CompiledAccess;

    std::string format(const char *fmt, auto... args)
    {
        std::string text(static_cast<size_t>(std::snprintf(nullptr, 0, fmt, args...)), '\0');
        std::snprintf(text.data(), text.size() + 1u, fmt, args...);
        return text;
    }

    std::string access(const A::Access &value)
    {
        return format("{%uu, %uu}", unsigned(value.reg), unsigned(value.lanes));
    }

    std::string usage(const A::Usage &u)
    {
        return format(".vfRead = {{%s, %s}}, .vfWrite = %s, .vfReadCount = %uu, .viRead = %uu, .viWrite = %uu, ",
                      access(u.vfRead[0]).c_str(), access(u.vfRead[1]).c_str(), access(u.vfWrite).c_str(),
                      unsigned(u.vfReadCount), unsigned(u.viRead), unsigned(u.viWrite)) +
               format(".accRead = %uu, .accWrite = %uu, .latency = %uu, .vfLatency = %uu, .viLatency = %uu, ",
                      unsigned(u.accRead), unsigned(u.accWrite), unsigned(u.latency), unsigned(u.vfLatency),
                      unsigned(u.viLatency)) +
               format(".pipeline = static_cast<A::Pipeline>(%u), .waitQ = %d, .waitP = %d, .readsClip = %d, "
                      ".writesClip = %d, .delaysNextBranchRead = %d, .reserved = %d",
                      unsigned(u.pipeline), int(u.waitQ), int(u.waitP), int(u.readsClip), int(u.writesClip),
                      int(u.delaysNextBranchRead), int(u.reserved));
    }

    template <A::Kind K, A::Operand O, bool ToAcc>
    bool matchFmac(A::UpperHandler handler, std::string &call)
    {
        if (handler != A::fmacHandler<K, O, ToAcc>())
            return false;
        call = format("A::fmac<A::Kind(%u), A::Operand(%u), %s>", unsigned(K), unsigned(O), ToAcc ? "true" : "false");
        return true;
    }

    template <A::Kind K>
    bool matchKind(A::UpperHandler handler, std::string &call)
    {
        return matchFmac<K, A::Operand::Broadcast, false>(handler, call) || matchFmac<K, A::Operand::Broadcast, true>(handler, call) ||
               matchFmac<K, A::Operand::Q, false>(handler, call) || matchFmac<K, A::Operand::Q, true>(handler, call) ||
               matchFmac<K, A::Operand::I, false>(handler, call) || matchFmac<K, A::Operand::I, true>(handler, call) ||
               matchFmac<K, A::Operand::Vector, false>(handler, call) || matchFmac<K, A::Operand::Vector, true>(handler, call);
    }

    std::string upperCall(uint32_t upper)
    {
        const A::UpperHandler handler = A::upperHandler(upper);
        std::string call;
        if (handler == A::nopHandler())
            call = "A::upperNop";
        else if (!(matchKind<A::Kind::Add>(handler, call) || matchKind<A::Kind::Sub>(handler, call) ||
                   matchKind<A::Kind::Madd>(handler, call) || matchKind<A::Kind::Msub>(handler, call) ||
                   matchKind<A::Kind::Mul>(handler, call)))
            call = "A::upperGeneric";
        return call + format("(vu, 0x%08Xu)", upper);
    }
}

int main(int argc, char **argv)
{
    if (argc < 3)
    {
        std::fprintf(stderr, "usage: %s <out.cpp> <image.bin>...\n", argv[0]);
        return 2;
    }
    std::string out = "// Generated by ps2_vu1_compile. Do not edit.\n"
                      "#include \"../lib/vu/ps2_vu1_step.h\"\n\n"
                      "namespace\n{\n    using A = Vu1CompiledAccess;\n"
                      "    using PairFn = A::Result (*)(VU1Interpreter &, uint64_t, uint8_t *, uint32_t, GS &, PS2Memory *);\n";
    VU1Interpreter vu;
    for (int arg = 2; arg < argc; ++arg)
    {
        std::vector<uint8_t> code(A::kCodeSize);
        FILE *in = std::fopen(argv[arg], "rb");
        if (!in || std::fread(code.data(), 1, code.size(), in) != code.size())
        {
            std::fprintf(stderr, "%s: not a %u-byte VU1 code image\n", argv[arg], A::kCodeSize);
            return 1;
        }
        std::fclose(in);
        const uint64_t hash = A::hash(code.data(), static_cast<uint32_t>(code.size()));
        std::vector<uint8_t> live(code.size() / 8u);
        A::flagLiveness(code.data(), static_cast<uint32_t>(code.size()), reinterpret_cast<bool *>(live.data()));
        const std::string id = format("%016llx", static_cast<unsigned long long>(hash));

        std::string table;
        for (uint32_t pc = 0; pc < code.size(); pc += 8u)
        {
            const A::Pair d = A::decode(vu, code.data(), pc);
            if (d.upperUsage.reserved || d.lowerUsage.reserved)
            {
                table += "        nullptr,\n";
                continue;
            }
            const std::string name = format("p%s_%04x", id.c_str(), pc);
            out += format("\n    A::Result %s(VU1Interpreter &vu, uint64_t budgetEnd, uint8_t *vuData, uint32_t dataSize, GS &gs, "
                          "PS2Memory *memory)\n    {\n",
                          name.c_str());
            out += format("        static constexpr A::Pair d{.lower = 0x%08Xu, .upper = 0x%08Xu, .upperHandler = nullptr,\n",
                          d.lower, d.upper);
            out += "            .lowerUsage = {" + usage(d.lowerUsage) + "},\n";
            out += "            .upperUsage = {" + usage(d.upperUsage) + "},\n";
            out += format("            .iBit = %d, .eBit = %d, .mBit = %d, .dBit = %d, .tBit = %d, .upperVfShadowReg = %uu, "
                          ".suppressedLowerVf = %uu, .writtenVi = %uu};\n",
                          int(d.iBit), int(d.eBit), int(d.mBit), int(d.dBit), int(d.tBit), unsigned(d.upperVfShadowReg),
                          unsigned(d.suppressedLowerVf), unsigned(d.writtenVi));
            out += format("        return A::step(vu, d, %s, budgetEnd, [&]() { %s; },\n", live[pc / 8u] ? "true" : "false",
                          upperCall(d.upper).c_str());
            out += format("                       [&]() { A::lower(vu, 0x%08Xu, vuData, dataSize, gs, memory, 0x%08Xu); });\n    }\n",
                          d.lower, d.upper);
            table += "        &" + name + ",\n";
        }
        out += format("\n    constexpr PairFn kTable%s[%u] = {\n", id.c_str(), A::kCodeSize / 8u) + table + "    };\n";
        out += format("\n    A::Result run%s(VU1Interpreter &vu, uint64_t budgetEnd, uint8_t *vuData, uint32_t dataSize, GS &gs, "
                      "PS2Memory *memory)\n    {\n"
                      "        while (A::running(vu, budgetEnd))\n        {\n"
                      "            const uint32_t pc = A::pc(vu);\n"
                      "            const PairFn pair = (pc & 7u) == 0u && pc < %uu ? kTable%s[pc >> 3] : nullptr;\n"
                      "            if (!pair)\n                return A::Result::Next;\n"
                      "            if (const A::Result result = pair(vu, budgetEnd, vuData, dataSize, gs, memory); result != A::Result::Next)\n"
                      "                return result;\n"
                      "        }\n        return A::Result::Stop;\n    }\n",
                      id.c_str(), A::kCodeSize, id.c_str());
        out += format("\n    const bool kRegistered%s = (A::registerProgram(0x%sull, &run%s), true);\n", id.c_str(), id.c_str(), id.c_str());
        std::printf("%s -> %s\n", argv[arg], id.c_str());
    }
    out += "}\n";
    FILE *file = std::fopen(argv[1], "wb");
    if (!file || std::fwrite(out.data(), 1, out.size(), file) != out.size())
    {
        std::fprintf(stderr, "cannot write %s\n", argv[1]);
        return 1;
    }
    std::fclose(file);
    return 0;
}
